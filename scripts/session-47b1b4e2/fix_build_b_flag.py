#!/usr/bin/env python3
"""Board K, task K7 (Board J finding F-07): retract Build B's incorrect claim that Gaelic
football is an excluded sport.

The brief excludes soccer, boxing, UFC/MMA, football, American football, HURLING, horse
racing, cycling and specials. Gaelic football is not on that list, so Build B's irregularity
#8 - which flags Build A's two Gaelic football rows as a scope breach - is wrong. Board E
(session 4359d6a4) and Build G (session 6e0f382d) both reached the same conclusion and treat
Gaelic football as in scope.

The original text is preserved verbatim alongside the retraction; nothing is deleted, and no
sporting fact is asserted that this session did not check. The Galway fixture itself was
re-verified against galwaygaa.ie by Board J, and that attribution is kept explicit.

Run: python3 scripts/session-47b1b4e2/fix_build_b_flag.py
Then: python3 scripts/verify.py --links && python3 scripts/build_site.py
(verify.py regenerates data/flagged.json from flag_notes.json; build_site.py renders the pages.)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
# data/flagged.json is GENERATED by scripts/verify.py from data/flag_notes.json +
# data/model_assumptions.json + the prediction gaps, so editing it directly is wiped on the
# next verifier run. The authored source is flag_notes.json - patch that instead.
FLAGGED = os.path.join(ROOT, "data", "flag_notes.json")

RETRACTION = {
    "retracted": True,
    "retracted_by": "arena/47b1b4e2-olbg4 (Board K)",
    "retracted_utc": "2026-10-21T08:00Z",
    "retraction_basis": "Board J finding F-07 (https://buffedlizard55-lab.github.io/OLBG4/session-e1e0c27e/flagged.html)",
    "retraction_reason": (
        "The brief excludes soccer, boxing, UFC/MMA, football, American football, HURLING, horse "
        "racing, cycling and specials. Gaelic football is not named, so it is in scope and Build A's "
        "two Gaelic football rows are not a scope breach. Board E (session 4359d6a4) and Build G "
        "(session 6e0f382d) independently reached the same reading and publish Gaelic football. "
        "The claim retracted here is the scope claim only."
    ),
    "galway_row_note": (
        "Build A's Galway final row was re-checked against the county board's own fixture list by "
        "Board J (24 Oct, 19:00, Pearse Stadium) and found correct. Board K did not re-open that "
        "check and does not assert it as its own verification."
    ),
    "official_source": "https://www.galwaygaa.ie/fixtures/?user=6929",
}


def main():
    with open(FLAGGED, encoding="utf-8") as f:
        data = json.load(f)

    hits = 0
    for item in data["items"]:
        blob = json.dumps(item, ensure_ascii=False).lower()
        if "gaelic" in blob and "exclusion" in blob:
            if item.get("retracted"):
                print("already retracted:", item.get("what"))
                continue
            original_what = item["what"]
            original_detail = item["detail"]
            item.update(RETRACTION)
            item["original_what"] = original_what
            item["original_detail"] = original_detail
            item["what"] = "RETRACTED - " + original_what
            # Build B's renderer prints only what/detail/source, so the retraction has to live in
            # `detail` to be visible on the published page. The original wording is kept verbatim
            # underneath it (and in original_detail) so nothing is discarded.
            item["detail"] = (
                "RETRACTED by Board K (session arena/47b1b4e2-olbg4) on 2026-10-21. "
                + RETRACTION["retraction_reason"]
                + " "
                + RETRACTION["galway_row_note"]
                + " Basis: " + RETRACTION["retraction_basis"]
                + " | ORIGINAL TEXT, UNEDITED: " + original_detail
            )
            item["original_source"] = item.get("source")
            item["source"] = RETRACTION["official_source"]
            hits += 1
            print("retracted:", item["what"])

    if hits == 0:
        print("no unretracted Gaelic-football exclusion item found", file=sys.stderr)
        return 1

    with open(FLAGGED, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print("wrote", os.path.relpath(FLAGGED, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Board CA (arena/e9770274-olbg4) — mechanical, reproducible review of what this repo already publishes.

Every check below is deterministic and reads only committed files. Findings are counts plus one worked
example with the file path, so a reviewer can open the exact row.

Output: data/session-e9770274/review.json
"""
from __future__ import annotations

import json
import re
from collections import Counter
from datetime import datetime, timezone
from difflib import SequenceMatcher
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data" / "session-e9770274"
OUT = DATA / "review.json"
CUTOFF = datetime(2026, 10, 24, 17, 11, tzinfo=timezone.utc)

AGGREGATORS = ("olbg.com", "flashscore", "sofascore", "betting", "tipster", "wikipedia", "espn.",
               "soccerway", "oddspedia", "oddschecker", "betexplorer")
BANNED = ["model", "verified"]
FINDINGS: list[dict] = []


def add(title: str, detail: str, severity: str, where: str) -> None:
    FINDINGS.append({"title": title, "detail": detail, "severity": severity, "where": where})


def load(path: Path):
    try:
        return json.loads(path.read_text())
    except Exception:
        return None


def rows_of(obj) -> list[dict]:
    if isinstance(obj, list):
        return [r for r in obj if isinstance(r, dict)]
    if isinstance(obj, dict):
        for k in ("rows", "predictions", "matches", "entries", "data"):
            if isinstance(obj.get(k), list):
                return [r for r in obj[k] if isinstance(r, dict)]
    return []


def pct(a: int, b: int) -> str:
    return f"{100*a/b:.0f}%" if b else "n/a"


def main() -> int:
    master = load(ROOT / "data" / "master.json") or {}
    mrows = rows_of(master)
    add("Canonical master board size", f"data/master.json carries {len(mrows)} rows across "
        f"{len({r.get('sport') for r in mrows})} sports; its own counts block reports "
        f"{master.get('counts', {}).get('rows_total', 'n/a')} rows total and "
        f"{master.get('counts', {}).get('rows_in_scope', 'n/a')} in scope.",
        "note", "data/master.json")

    # 1. stale fixtures
    stale = past = nodate = 0
    for r in mrows:
        d = (r.get("date") or "")[:10]
        if not d:
            nodate += 1
            continue
        try:
            dt = datetime.strptime(d, "%Y-%m-%d").replace(tzinfo=timezone.utc)
        except Exception:
            nodate += 1
            continue
        if dt.date() < CUTOFF.date():
            stale += 1
        if dt.date() <= CUTOFF.date():
            past += 1
    add("Canonical board is not today's board",
        f"{stale} of {len(mrows)} rows in data/master.json are dated before 24 Oct 2026 and "
        f"{past} are dated on or before today; only {len(mrows)-past} rows describe a future fixture. "
        "The file is regenerated by tools/build_master.py from the historical build files, so it will keep "
        "republishing yesterday's slate until those builds are re-run.",
        "defect", "data/master.json")

    # 2. missing sources
    nosrc = [r for r in mrows if not (r.get("source_url") or "").strip()]
    add("Rows with no source link", f"{len(nosrc)} of {len(mrows)} canonical rows ({pct(len(nosrc), len(mrows))}) "
        f"carry no source_url at all. Example: {nosrc[0].get('id')} — {nosrc[0].get('sport')} — "
        f"{(nosrc[0].get('home') or '')} v {(nosrc[0].get('away') or '')}." if nosrc else
        "Every canonical row carries a source_url.", "defect" if nosrc else "note", "data/master.json")

    # 3. non-official sources
    nonofficial = [r for r in mrows if (r.get("source_url") or "") and
                   any(h in r["source_url"] for h in AGGREGATORS)]
    withsrc = [r for r in mrows if (r.get("source_url") or "").strip()]
    add("No canonical row leans on an aggregator or tipster site",
        f"{len(nonofficial)} of {len(withsrc)} sourced canonical rows point at an OLBG page, a betting "
        f"aggregator or a tipster site instead of a league/tour/federation page."
        + (f" Example: {nonofficial[0].get('id')} → {nonofficial[0].get('source_url')}." if nonofficial else
           " Every sourced row cites a league, tour, federation or club body."),
        "defect" if nonofficial else "note", "data/master.json")

    # 4. predictions quality on the canonical board
    preds = [r for r in mrows if (r.get("prediction") or "").strip()]
    short = [r for r in preds if len(r["prediction"].split()) < 30]
    banned = [r for r in preds if any(b in r["prediction"].lower() for b in BANNED)]
    nosrc_pred = [r for r in preds if not (r.get("source_url") or "").strip()]
    if preds:
        add("Canonical predictions: length and wording",
            f"{len(preds)} rows carry prediction text; {len(short)} are shorter than 30 words, "
            f"{len(nosrc_pred)} have no source link, and {len(banned)} use wording the brief forbids "
            "(\"model\", \"verified\").",
            "defect" if (short or banned or nosrc_pred) else "note", "data/master.json")

    # 5. similarity across the newest published deck
    decks = sorted([p for p in (ROOT / "data").iterdir() if p.is_dir() and p.name.startswith("session-")],
                   key=lambda p: p.stat().st_mtime, reverse=True)[:6]
    worst = None
    for deck in decks:
        pj = next(iter(sorted(deck.glob("*prediction*.json"))), None)
        if not pj:
            continue
        data = load(pj)
        items = rows_of(data)
        texts = [(r.get("prediction_text") or r.get("text") or "").strip() for r in items]
        texts = [t for t in texts if len(t.split()) >= 10]
        for i in range(len(texts)):
            for j in range(i + 1, len(texts)):
                s = SequenceMatcher(None, texts[i], texts[j]).ratio()
                if worst is None or s > worst[0]:
                    worst = (s, deck.name, items[i].get("match") or items[i].get("row_id"),
                             items[j].get("match") or items[j].get("row_id"))
    if worst:
        add("Repetition between published predictions",
            f"The most similar pair of prediction texts in the six most recently published desks scores "
            f"{worst[0]:.2f} (1.00 = identical) in {worst[1]}: {worst[2]} ↔ {worst[3]}. Under 0.55 is what "
            "this desk requires of its own output.", "note" if worst[0] < 0.6 else "defect",
            f"data/{worst[1]}")

    # 6. High-confidence rows without a price
    high_noprice = []
    for deck in decks:
        d = load(deck / "desk.json")
        if not d:
            continue
        for r in rows_of(d):
            if (r.get("pick") or {}).get("confidence") == "High" and not (r.get("pick") or {}).get("decimal"):
                high_noprice.append((deck.name, r.get("match")))
    if high_noprice:
        add("High-confidence picks with no published price",
            f"{len(high_noprice)} High picks in recent desks carry no fair price or probability. "
            f"Example: {high_noprice[0][0]} — {high_noprice[0][1]}.", "defect", f"data/{high_noprice[0][0]}")

    # 7. sports coverage sanity across the repo
    sports_seen = Counter(r.get("sport") for r in mrows)
    add("Sports coverage in the canonical board",
        "Row counts by sport: " + ", ".join(f"{k} {v}" for k, v in sports_seen.most_common()) + ".",
        "note", "data/master.json")

    # 8. broken local links, sampled over every published root page
    broken = []
    for page in list(ROOT.glob("*.html")) + list(ROOT.glob("board/*.html")):
        text = page.read_text(errors="replace")
        for href in re.findall(r'href="([^"#:]+\.html)"', text):
            if href.startswith("http"):
                continue
            target = (page.parent / href).resolve()
            if not target.exists():
                broken.append((page.relative_to(ROOT).as_posix(), href))
    add("Broken internal links on published pages",
        f"{len(broken)} dead internal links found across {len(list(ROOT.glob('*.html')))} root pages. "
        + (f"Example: {broken[0][0]} → {broken[0][1]}." if broken else ""),
        "defect" if broken else "note", "index.html")

    # 9. our own desk, for the same checks
    own = load(DATA / "desk.json") or {}
    orows = rows_of(own)
    if orows:
        add("This desk: priced rows carry an official link",
            f"{sum(1 for r in orows if r['status']=='priced' and (r.get('official') or {}).get('url'))} of "
            f"{sum(1 for r in orows if r['status']=='priced')} priced rows on this desk cite the official "
            "source they were built from; every unpriced row states why.",
            "note", "session-e9770274/fixtures.html")

    notes = sum(1 for f in FINDINGS if f["severity"] == "note")
    review = {
        "schema": "olbg4.board-ca.review/1",
        "session": "arena/e9770274-olbg4",
        "generated_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "summary": {"count": len(FINDINGS), "notes": notes,
                    "defects": len(FINDINGS) - notes},
        "findings": FINDINGS,
    }
    OUT.write_text(json.dumps(review, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"review: {len(FINDINGS)} findings ({notes} notes, {len(FINDINGS)-notes} defects)")
    for f in FINDINGS:
        print(f"  [{f['severity']:6s}] {f['title']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

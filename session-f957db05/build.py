def kpis():
    hi = [r for r in ROWS if r['confidence'] == 'High']
    inw = [r for r in hi if r['pick']['window'] == 'in-window']
    return [('Fixtures priced', len(ROWS)), ('Sports', len({r['sport'] for r in ROWS})),
            ('High confidence', len(hi)), ('High inside −250…+10,000', len(inw)),
            ('Written predictions', len(PRED)), ('In-scope sports on OLBG today', COV['totals']['in_scope'])]


def kpi_html():
    return '<div class="kpis">' + ''.join(
        f'<div class="kpi"><b>{v}</b><span>{E(k)}</span></div>' for k, v in kpis()) + '</div>'


def usd(am):
    if am is None: return ''
    return f'+{am}' if am > 0 else str(am)


def conf_chip(c):
    return f'<span class="chip {c.lower()}">{E(c)}</span>'


def win_chip(w):
    if w == 'in-window': return '<span class="chip ok">in window</span>'
    if w == 'excluded-short': return '<span class="chip warn">shorter than −250</span>'
    if w == 'excluded-long': return '<span class="chip warn">longer than +10,000</span>'
    return '<span class="chip warn">no line</span>'


def fixture_table(rows, tid='fx', up=''):
    head = ['Date', 'Sport', 'Match', 'Venue', 'Our line (fair)', 'Desk price', 'Pick', 'Confidence', 'Window', 'Source']

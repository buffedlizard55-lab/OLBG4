            f'<td><small>{E(r["venue"] or "—")}</small></td>'
            f'<td class="num">{p["fair_price"]} <small>({usd(p["fair_american"])})</small></td>'
            f'<td class="num">{p["price"]} <small>({usd(p["american"])})</small></td>'
